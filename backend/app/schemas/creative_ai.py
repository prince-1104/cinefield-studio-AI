"""Pydantic schemas for AI Creative Director, Website Analysis, and Asset Extraction."""

from typing import Literal
from pydantic import BaseModel, Field, HttpUrl


class WebsiteAssetCandidate(BaseModel):
    """Discovered media asset from a website (logo, product image, etc.)."""
    url: str
    asset_type: Literal["logo", "product", "screenshot", "favicon"] = "product"
    title: str | None = None
    width: int | None = None
    height: int | None = None


class WebsiteAnalysisRequest(BaseModel):
    """Input payload to analyze a business or product website."""
    url: str = Field(..., description="Public website URL (e.g. https://example.com)")


class WebsiteAnalysisResult(BaseModel):
    """Structured extraction of brand, messaging, and media assets from a website."""
    url: str
    domain: str
    title: str
    description: str
    headings: list[str] = Field(default_factory=list)
    key_content: str = ""
    brand_colors: list[str] = Field(default_factory=list)
    logo_candidates: list[WebsiteAssetCandidate] = Field(default_factory=list)
    product_image_candidates: list[WebsiteAssetCandidate] = Field(default_factory=list)


class CreativeBriefRequest(BaseModel):
    """Input payload instructing Claude to architect a full production brief."""
    prompt: str = Field(..., min_length=2, description="Vague idea or creative direction from user")
    website_url: str | None = None
    website_data: WebsiteAnalysisResult | None = None
    video_category: str = Field(
        default="Advertisement",
        description="Category: Advertisement, Branding, Product Promotion, Product Launch, Movie, Micro Drama, etc.",
    )
    target_duration: int = Field(default=60, ge=5, le=120)
    aspect_ratio: str = Field(default="16:9")
    creative_style: str | None = None
    target_audience: str | None = None
    language: str = Field(default="en")
    narration_preference: str = Field(default="Dramatic Voiceover")
    cta: str | None = None


class GeneratedBriefResponse(BaseModel):
    """Production-ready creative brief generated by Claude Creative Director."""
    product_name: str
    brief: str
    tone: str
    audience: str
    cta: str
    target_duration: int
    shot_count: int
    aspect_ratio: str
    video_category: str
    suggested_music_mood: str
    creative_reasoning: str
    hook: str | None = None
    narration_preview: str | None = None
    provider_used: str = "claude"


class ImportAssetRequest(BaseModel):
    """Request to safely download an extracted website image and persist as an artifact."""
    url: str
    project_id: str | None = None
    asset_type: Literal["product", "logo"] = "product"


class ImportAssetResponse(BaseModel):
    """Result of downloaded and persisted artifact."""
    asset_path: str
    url: str
    file_name: str
    size: int
    content_type: str

